        private const double BoxSize = 24;

        /// <summary>工具名 → 路径数据。没有登记的工具会退回虚线占位块。</summary>
        private static readonly Dictionary<string, string> Data =
            new Dictionary<string, string>(StringComparer.Ordinal)
            {
                { "硬件信息", HardwareInfo }
            };

        public static bool Has(string title)
        {
            return !string.IsNullOrEmpty(title) && Data.ContainsKey(title);
        }

        /// <summary>24 px 图标；未登记的返回 null，让调用方画占位块。</summary>
        public static FrameworkElement Build(string title, Brush fill)
        {
            string data;
            if (string.IsNullOrEmpty(title) || !Data.TryGetValue(title, out data)) return null;

            Geometry geometry = Geometry.Parse(data);
            PathGeometry path = geometry as PathGeometry;
            if (path != null)
            {
                path.FillRule = FillRule.Nonzero;
            }
            else
            {
                GeometryGroup group = new GeometryGroup { FillRule = FillRule.Nonzero };
                group.Children.Add(geometry);
                geometry = group;
            }

            Path shape = new Path
            {
                Data = geometry,
                Fill = fill,
                Stretch = Stretch.Uniform,
                SnapsToDevicePixels = true
            };

            Viewbox box = new Viewbox
            {
                Width = BoxSize,
                Height = BoxSize,
                HorizontalAlignment = HorizontalAlignment.Center,
                Child = shape
            };
            return box;
        }

