    /// 常用工具格里的小图标：矢量路径数据（SVG path 字符串）+ 统一的 24 px 盒子。
    ///
    /// 为什么是路径而不是图片：图标要按 DPI 放大、还要跟着主题色走，位图两条都做不到；
    /// 而且图标只是一串数字，加一个新工具不用碰绘制代码。
    /// SVG 默认是 nonzero 填充规则，WPF 的 Geometry.Parse 默认是 evenodd——不显式改过来，
    /// 带镂空的图标会糊成一个实心块（实测：显示器里的心电图被填掉）。
    /// </summary>
    internal static class ToolIcons
